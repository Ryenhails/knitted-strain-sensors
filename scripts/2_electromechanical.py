"""Step 2 - paper Section V (RQ1): electromechanical properties of the 14 designs.

Works on the medium-rate block of every sample (step 1) and produces, in the
order of the paper:

  Table IV  metrics per design: mean +- SD over 3 tensile and 2 bending samples
            -> results/tables/table4_electromechanical.csv and .tex
  Fig. 5    resistance-strain curves of both rigs  -> results/figures/fig5_curves.pdf
  V-A       numbers quoted for the tensile tests   -> results/numbers_section5.json
  V-B       numbers quoted for the bending tests   -> results/numbers_section5.json
  Fig. 6    do the two rigs rank the designs alike?
            -> results/tables/fig6_cross_rig.csv, results/figures/fig6_cross_rig.pdf

    python scripts/2_electromechanical.py          (about 1 minute)
"""
import sys
import warnings
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # makes `knitsensor` importable
from knitsensor import config, data  # noqa: E402
from knitsensor.designs import LETTERS, STRUCTURES, label, stitch, structure  # noqa: E402
from knitsensor.plotting import GREY, INK, LABELS, LARGE, LIGHT, SMALL, paper_style, plt, save  # noqa: E402
from knitsensor.stats import spearman  # noqa: E402
from knitsensor.tables import mean_sd, read_csv, write_csv, write_json  # noqa: E402

METRICS = ['R0', 'GF', 'WR', 'LR', 'H', 'stab']               # the six metrics of Table IV
DECIMALS = {'R0': 2, 'GF': 0, 'WR': 1, 'LR': 1, 'H': 1, 'stab': 2}
BEST = {'GF': max, 'WR': max, 'LR': max, 'H': min, 'stab': min}   # printed in bold


# ------------------------------------------------------------------ Table IV

def table4(tensile, bending):
    """Mean and SD over the samples of each design, on each rig, plus the
    between/within ratio: SD of the 14 tensile design means / median within-design SD."""
    rows = {}
    for d in LETTERS:
        row = dict(design=d, structure=structure(d), stitch_size=stitch(d))
        for rig, samples in (('tensile', tensile), ('bending', bending)):
            mine = [s for s in samples if s['design'] == d]
            row[rig + '_n'] = len(mine)
            for m in METRICS:
                row['%s_%s_mean' % (rig, m)], row['%s_%s_sd' % (rig, m)] = mean_sd([s[m] for s in mine])
        rows[d] = row
    ratio = {m: float(np.std([rows[d]['tensile_%s_mean' % m] for d in LETTERS], ddof=1) /
                      np.median([rows[d]['tensile_%s_sd' % m] for d in LETTERS])) for m in METRICS}
    write_csv(config.TABLES / 'table4_electromechanical.csv', list(rows.values()))
    write_table4_tex(rows, ratio)
    return rows, ratio


def write_table4_tex(rows, ratio):
    best = {(rig, m): BEST[m](LETTERS, key=lambda d: rows[d]['%s_%s_mean' % (rig, m)])
            for rig in ('tensile', 'bending') for m in BEST}
    lines = []
    for name, smaller, larger in STRUCTURES:
        for d in (smaller, larger):
            cells = [name if d == smaller else '', '%g' % stitch(d)]
            for rig in ('tensile', 'bending'):
                for m in METRICS:
                    cell = '%.*f$\\pm$%.*f' % (DECIMALS[m], rows[d]['%s_%s_mean' % (rig, m)],
                                               DECIMALS[m], rows[d]['%s_%s_sd' % (rig, m)])
                    cells.append('\\textbf{%s}' % cell if best.get((rig, m)) == d else cell)
            lines.append(' & '.join(cells) + ' \\\\')
        lines.append('\\addlinespace[1pt]')
    lines[-1] = '\\midrule'
    lines.append('\\multicolumn{2}{l}{between/within SD} & ' +
                 ' & '.join('%.1f$\\times$' % ratio[m] for m in METRICS) + ' & & & & & & \\\\')
    path = config.TABLES / 'table4_electromechanical.tex'
    path.write_text('% Rows of Table IV, generated by scripts/2_electromechanical.py\n' + '\n'.join(lines) + '\n')
    print('  wrote', path)


# ------------------------------------------------------------------ Fig. 5

def fig5(bending):
    """Mean tensile curve of the 3 samples (+- SD band, dot at the peak) and the
    curve of the new bending sample, per structure and stitch size."""
    curves = {}
    for r in read_csv(config.BLOCKS / 'curves.csv'):
        curves.setdefault((r['rig'], r['sample']), {})[round(r['strain'], 1)] = r['dRR0']
    grid = np.round(np.arange(0, 1001) * 0.1, 1)
    on_grid = lambda c: np.array([c.get(g, np.nan) for g in grid])
    new_sample = {s['design']: s for s in bending if s['history'] == 'new'}

    fig, axes = plt.subplots(2, 4, figsize=(7.16, 2.95))
    axes = axes.ravel()
    for ax, (name, smaller, larger) in zip(axes, STRUCTURES):
        for d, colour in ((smaller, SMALL), (larger, LARGE)):
            keep = grid <= 59.5                                  # stop short of the turn-around
            tensile = np.vstack([on_grid(c)[keep] for (rig, s), c in curves.items() if rig == 'tensile' and s[0] == d])
            with warnings.catch_warnings():                      # grid points reached by < 2 samples
                warnings.simplefilter('ignore', RuntimeWarning)
                x, mean, sd = grid[keep], np.nanmean(tensile, 0), np.nanstd(tensile, 0, ddof=1)
            ax.fill_between(x, mean - sd, mean + sd, color=colour, alpha=0.15, lw=0)
            ax.plot(x, mean, color=colour, lw=1.1)
            peak = int(np.nanargmax(mean))
            ax.plot(x[peak], mean[peak], 'o', ms=3.2, color=colour, mec='white', mew=0.5)
            s = new_sample[d]
            bend = on_grid(curves['bending', s['sample']])
            keep = grid <= s['stroke_strain'] - 0.5
            ax.plot(grid[keep], bend[keep], color=colour, lw=1.0, ls=(0, (3, 1.6)))
        ax.set_title(name, pad=3)
        ax.set_xlim(0, 66); ax.set_xticks([0, 20, 40, 60]); ax.set_ylim(bottom=0)
        ax.grid(color=LIGHT, lw=0.4); ax.set_axisbelow(True)
    for k in (0, 4):
        axes[k].set_ylabel(r'$\Delta R/R_0$')
    for k in (3, 4, 5, 6):
        axes[k].set_xlabel('strain (%)')
    axes[7].axis('off')
    from matplotlib.lines import Line2D
    from matplotlib.patches import Patch
    axes[7].legend([Line2D([], [], color=SMALL, lw=1.4), Line2D([], [], color=LARGE, lw=1.4),
                    (Patch(color='0.5', alpha=0.25, lw=0), Line2D([], [], color='0.33', lw=1.4)),
                    Line2D([], [], color='0.33', lw=1.2, ls=(0, (3, 1.6)))],
                   ['smaller stitch size', 'larger stitch size',
                    'tensile testing: mean of three\nsamples with $\\pm$SD shaded band',
                    'bending testing: preconditioned,\npreviously untested sample\n(not tensile-tested)'],
                   loc='upper left', bbox_to_anchor=(-0.05, 1.05), frameon=False, fontsize=6.5, handlelength=2.4)
    axes[7].text(-0.02, -0.08, 'loading direction, medium rate in both tests;\nelbow angle converted to strain\n'
                 '(0 to 150$^\\circ$ = 61 mm over $L_0$)', transform=axes[7].transAxes, fontsize=5.8, color=GREY,
                 va='top')
    fig.tight_layout(h_pad=1.0, w_pad=0.8)
    save(fig, 'fig5_curves')


# ------------------------------------------------------------------ Section V-A

def section_5a(tensile, design, ratio):
    """Numbers quoted in Section V-A (tensile tests)."""
    settling = read_csv(config.BLOCKS / 'tensile_settling.csv')
    blocks = read_csv(config.BLOCKS / 'tensile_blocks.csv')
    by_rate = {s['sample']: {b['rate']: b for b in blocks if b['sample'] == s['sample']} for s in tensile}
    mean_by_rate = {m: {rate: float(np.mean([v[rate][m] for v in by_rate.values()])) for rate in 'ABC'}
                    for m in ('GF', 'WR', 'LR', 'H')}
    tensile_mean = lambda m: {d: design[d]['tensile_%s_mean' % m] for d in LETTERS}

    def design_range(m):
        v = tensile_mean(m)
        lo, hi = min(v, key=v.get), max(v, key=v.get)
        return dict(min=v[lo], min_design=label(lo), max=v[hi], max_design=label(hi), fold=v[hi] / v[lo])

    drift_share = {d: 100 * float(np.mean([s['stab_drift_share'] for s in tensile if s['design'] == d]))
                   for d in LETTERS}
    return {
        # preconditioning: median over the 42 samples of (mean of last 50 cycles / first 50) - 1
        'GF_change_within_block_median_pct': {
            b: 100 * float(np.median([s['GF_change'] for s in settling if s['block'] == b]))
            for b in ('precondition', 'block1', 'block2', 'block3')},
        'R0_change_within_block_median_pct': {
            b: 100 * float(np.median([s['R0_change'] for s in settling if s['block'] == b]))
            for b in ('block1', 'block2', 'block3')},
        # baseline resistance: in how many of the 7 structures the larger stitch size is higher
        'larger_stitch_size_has_higher': {
            m: sum(tensile_mean(m)[larger] > tensile_mean(m)[smaller] for _, smaller, larger in STRUCTURES)
            for m in METRICS},
        # sensitivity and loading rate
        'GF_design_range': design_range('GF'),
        'rate': dict(n_samples=len(by_rate),
                     GF_fast_higher_than_slow=sum(v['C']['GF'] > v['A']['GF'] for v in by_rate.values()),
                     mean_by_rate=mean_by_rate,
                     WR_LR_H_largest_shift=max(abs(mean_by_rate[m][a] - mean_by_rate[m][b])
                                               for m in ('WR', 'LR', 'H') for a in 'ABC' for b in 'ABC')),
        # working range, linear range, hysteresis, cyclic stability
        'peak_strain_median_pct': float(np.median([s['peak_x'] for s in tensile])),
        'fall_from_peak_max_pct': float(np.nanmax([s['fall_pct'] for s in tensile])),
        'LR_share_of_WR_median_pct': 100 * float(np.median([design[d]['tensile_LR_mean'] / design[d]['tensile_WR_mean']
                                                            for d in LETTERS])),
        'LR_equals_WR_designs': sum(abs(design[d]['tensile_LR_mean'] - design[d]['tensile_WR_mean']) < 1e-9
                                    for d in LETTERS),
        'H_design_range': design_range('H'),
        'stab_design_range': design_range('stab'),
        'stab_drift_share_pct': dict(min=min(drift_share.values()), max=max(drift_share.values()),
                                     median=float(np.median(list(drift_share.values()))),
                                     max_design=label(max(drift_share, key=drift_share.get))),
        'between_within_sd_ratio': ratio,
    }


# ------------------------------------------------------------------ Section V-B and Fig. 6

def rank_agreement(tensile, bending, design):
    """Spearman rho between the rigs over the 14 designs, for two pairings:
    same-sample  the 14 samples tested on both rigs (tensile value vs bending value)
    design-mean  tensile design mean vs the bending sample new to the bending test."""
    tensile_by_sample = {s['sample']: s for s in tensile}
    tested = sorted((s for s in bending if s['history'] == 'tensile-tested'), key=lambda s: s['sample'])
    new = {s['design']: s for s in bending if s['history'] == 'new'}
    rows = []
    for m in METRICS:
        rows.append(dict(metric=m, pairing='same-sample',
                         **spearman([tensile_by_sample[s['sample']][m] for s in tested], [s[m] for s in tested])))
        rows.append(dict(metric=m, pairing='design-mean',
                         **spearman([design[d]['tensile_%s_mean' % m] for d in LETTERS], [new[d][m] for d in LETTERS])))
    write_csv(config.TABLES / 'fig6_cross_rig.csv', rows)
    return rows


def section_5b(bending, design, agreement):
    """Numbers quoted in Section V-B (bending tests), on the 14 new samples."""
    new = [s for s in bending if s['history'] == 'new']
    gf = [design[d]['bending_GF_mean'] for d in LETTERS]
    rho = lambda metrics: [r['rho'] for r in agreement if r['metric'] in metrics]
    return {
        'stroke_strain_pct': dict(min=min(s['stroke_strain'] for s in new), max=max(s['stroke_strain'] for s in new),
                                  median=float(np.median([s['stroke_strain'] for s in new]))),
        'peak_angle_median_deg': float(np.median([s['peak_angle'] for s in new])),
        'WR_start_deg': dict(min=min(s['WR_start_angle'] for s in new), max=max(s['WR_start_angle'] for s in new)),
        'GF_design_fold': max(gf) / min(gf),
        'rank_agreement_rho_range': {
            'GF_R0': [min(rho(['GF', 'R0'])), max(rho(['GF', 'R0']))],
            'stab': [min(rho(['stab'])), max(rho(['stab']))],
            'WR_LR_H': [min(rho(['WR', 'LR', 'H'])), max(rho(['WR', 'LR', 'H']))]},
    }


def fig6(agreement):
    rows = {(r['metric'], r['pairing']): r for r in agreement}
    order = ['GF', 'R0', 'stab', 'WR', 'LR', 'H']                # row order of the paper
    fig, ax = plt.subplots(figsize=(3.5, 1.75))
    for k, m in enumerate(order):
        for pairing, dy, face in (('same-sample', -0.17, INK), ('design-mean', 0.17, 'white')):
            r = rows[m, pairing]
            ax.plot([r['ci_lo'], r['ci_hi']], [k + dy] * 2, color=GREY, lw=1.0)
            ax.plot(r['rho'], k + dy, 'o', ms=4.5, mfc=face, mec=INK, mew=1.0,
                    label=pairing + ' pairing' if k == 0 else None)
    for x in (-0.5, 0.5):
        ax.axvline(x, color=LIGHT, lw=0.4, zorder=0)
    ax.axvline(0, color='0.33', lw=0.6, zorder=0)
    ax.set_yticks(range(len(order)), [LABELS[m] for m in order])
    ax.set_ylim(len(order) - 0.5, -0.5)
    ax.tick_params(axis='y', length=0)
    ax.set_xlim(-1, 1); ax.set_xticks([-1, -0.5, 0, 0.5, 1], ['$-1$', '$-0.5$', '0', '0.5', '1'])
    ax.set_xlabel(r'rank correlation $\rho$ between tensile and bending tests')
    ax.legend(loc='upper left', frameon=False, fontsize=6.5, handletextpad=0.3, borderaxespad=0.1)
    save(fig, 'fig6_cross_rig')


# ------------------------------------------------------------------ main

def main():
    paper_style()
    tensile = [r for r in read_csv(config.BLOCKS / 'tensile_blocks.csv') if r['rate'] == config.MEDIUM]
    bending = [r for r in read_csv(config.BLOCKS / 'bending_blocks.csv') if r['rate'] == config.MEDIUM]
    write_csv(config.TABLES / 'samples_tensile.csv', tensile)      # 42 samples, medium-rate block
    write_csv(config.TABLES / 'samples_bending.csv', bending)      # 28 samples, medium-rate block

    design, ratio = table4(tensile, bending)
    temperature, humidity = data.room_conditions()
    fig5(bending)
    agreement = rank_agreement(tensile, bending, design)
    fig6(agreement)
    write_json(config.RESULTS / 'numbers_section5.json', {
        'IV-B': {'bending_rate_mm_s': {r: v * config.STROKE_MM / config.STROKE_DEG
                                       for r, v in config.BENDING_RATE_DEG_S.items()}},
        'Table IV': {'room_temperature_C': [float(np.nanmin(temperature)), float(np.nanmax(temperature))],
                     'room_humidity_pct': [float(np.nanmin(humidity)), float(np.nanmax(humidity))],
                     'between_within_sd_ratio': ratio},
        'V-A': section_5a(tensile, design, ratio),
        'V-B': section_5b(bending, design, agreement),
    })


if __name__ == '__main__':
    main()
