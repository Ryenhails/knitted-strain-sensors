"""Step 4 - paper Sections VI-B and VI-C (RQ2): joint-angle estimation error, and
whether the tensile metrics predict it.

Reads the predictions of step 3 and the tensile metrics of step 2, and produces:

  VI-B  error of every recording  -> results/tables/joint_angle_errors.csv
        Table V                   -> results/tables/table5_joint_angle.csv and .tex
        numbers quoted in VI-B    -> results/numbers_section6.json
  VI-C  Fig. 7: Spearman rho between each tensile metric and the RMSE
                                  -> results/tables/fig7_rq2.csv, results/figures/fig7_rq2.pdf
        numbers quoted in VI-C    -> results/numbers_section6.json

    python scripts/4_joint_angle_error.py          (about 1 minute)
"""
import sys
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))   # makes `knitsensor` importable
from knitsensor import config, data, estimation  # noqa: E402
from knitsensor.designs import LETTERS, STRUCTURES, TABLE_ORDER, label, stitch, structure  # noqa: E402
from knitsensor.plotting import GREY, INK, LABELS, LIGHT, paper_style, plt, save  # noqa: E402
from knitsensor.stats import spearman  # noqa: E402
from knitsensor.tables import read_csv, write_csv, write_json  # noqa: E402

METRICS = ['R0', 'GF', 'WR', 'LR', 'H', 'stab']
ESTIMATORS = ['mlp', 'detr', 'rf']


# ------------------------------------------------------------------ Section VI-B

def recording_errors():
    """RMSE, MAE, R2 and share within 5 deg of every recording, head and estimator."""
    rows = []
    for rec in data.bending_recordings():
        for head in ('reg', 'cls'):
            path = config.PREDICTIONS / head / (rec['sample'] + '.npz')
            if not path.exists():
                sys.exit('%s is missing: run scripts/3_train_estimators.py first' % path)
            saved = np.load(path)
            for est in ESTIMATORS:
                res = {key[len(est) + 1:]: saved[key] for key in saved.files if key.startswith(est + '_')}
                row = dict(sample=rec['sample'], design=rec['design'], history=rec['history'],
                           head=head, estimator=est, **estimation.scores(res))
                if head == 'reg':
                    row['rmse_ci_lo'], row['rmse_ci_hi'] = estimation.rmse_interval(res['pred'] - res['angle'])
                rows.append(row)
    write_csv(config.TABLES / 'joint_angle_errors.csv', rows)
    return {(r['design'], r['history'], r['head'], r['estimator']): r for r in rows}


def table5(err):
    """Left: the new sample of each design; right: its tensile-tested sample."""
    rows = []
    for d in TABLE_ORDER:
        new = lambda est: err[d, 'new', 'reg', est]
        old = lambda est: err[d, 'tensile-tested', 'reg', est]
        rows.append(dict(design=d, structure=structure(d), stitch_size=stitch(d),
                         mlp_rmse=new('mlp')['rmse'], mlp_rmse_ci_lo=new('mlp')['rmse_ci_lo'],
                         mlp_rmse_ci_hi=new('mlp')['rmse_ci_hi'], mlp_mae=new('mlp')['mae'],
                         mlp_r2=new('mlp')['r2'], mlp_within5=new('mlp')['within5'],
                         detr_rmse=new('detr')['rmse'], rf_rmse=new('rf')['rmse'],
                         old_mlp_rmse=old('mlp')['rmse'], old_detr_rmse=old('detr')['rmse'],
                         old_rf_rmse=old('rf')['rmse']))
    write_csv(config.TABLES / 'table5_joint_angle.csv', rows)

    lines = []
    for name, smaller, larger in STRUCTURES:
        for r in rows:
            if r['design'] in (smaller, larger):
                lines.append('%s & %g & %.1f [%.1f, %.1f] & %.1f & %.3f & %.0f\\%% & %.1f & %.1f & %.1f & %.1f & %.1f \\\\' % (
                    name if r['design'] == smaller else '', r['stitch_size'], r['mlp_rmse'], r['mlp_rmse_ci_lo'],
                    r['mlp_rmse_ci_hi'], r['mlp_mae'], r['mlp_r2'], r['mlp_within5'], r['detr_rmse'],
                    r['rf_rmse'], r['old_mlp_rmse'], r['old_detr_rmse'], r['old_rf_rmse']))
        lines.append('\\addlinespace[1pt]')
    lines[-1] = '\\midrule'
    median = lambda k: float(np.median([r[k] for r in rows]))
    lines.append('median & & %.1f & %.1f & %.3f & %.0f\\%% & %.1f & %.1f & %.1f & %.1f & %.1f \\\\' % tuple(
        median(k) for k in ('mlp_rmse', 'mlp_mae', 'mlp_r2', 'mlp_within5', 'detr_rmse', 'rf_rmse',
                            'old_mlp_rmse', 'old_detr_rmse', 'old_rf_rmse')))
    path = config.TABLES / 'table5_joint_angle.tex'
    path.write_text('% Rows of Table V, generated by scripts/4_joint_angle_error.py\n' + '\n'.join(lines) + '\n')
    print('  wrote', path)


def section_6b(err):
    """Numbers quoted in Section VI-B (regression head)."""
    rmse = lambda est, hist='new': {d: err[d, hist, 'reg', est]['rmse'] for d in LETTERS}
    mlp, detr, rf = rmse('mlp'), rmse('detr'), rmse('rf')
    old_mlp, old_rf = rmse('mlp', 'tensile-tested'), rmse('rf', 'tensile-tested')
    ranked = sorted(LETTERS, key=mlp.get)
    difference = [old_mlp[d] - mlp[d] for d in LETTERS]
    median = lambda values: float(np.median(list(values)))
    return {
        'new_sample': dict(
            mlp_rmse_min=mlp[ranked[0]], mlp_rmse_min_design=label(ranked[0]),
            mlp_rmse_max=mlp[ranked[-1]], mlp_rmse_max_design=label(ranked[-1]),
            mlp_rmse_median=median(mlp.values()),
            mlp_r2_median=median(err[d, 'new', 'reg', 'mlp']['r2'] for d in LETTERS),
            mlp_within5_median=median(err[d, 'new', 'reg', 'mlp']['within5'] for d in LETTERS),
            rf_lower_than_mlp=sum(rf[d] < mlp[d] for d in LETTERS),
            rf_rmse_median=median(rf.values()),
            detr_minus_mlp_median=median(detr[d] - mlp[d] for d in LETTERS),
            detr_better_than_mlp=sum(detr[d] < mlp[d] for d in LETTERS),
            mlp_rmse_fold=mlp[ranked[-1]] / mlp[ranked[0]],
            two_smallest=[label(d) for d in ranked[:2]], two_largest=[label(d) for d in ranked[-2:]]),
        'tensile_tested_sample': dict(
            mlp_rmse_median=median(old_mlp.values()),
            paired_difference_median=median(difference),          # tensile-tested minus new
            paired_difference_min=min(difference), paired_difference_max=max(difference),
            rank_agreement_mlp=float(spearmanr([mlp[d] for d in LETTERS], [old_mlp[d] for d in LETTERS])[0]),
            rank_agreement_rf=float(spearmanr([rf[d] for d in LETTERS], [old_rf[d] for d in LETTERS])[0])),
    }


# ------------------------------------------------------------------ Section VI-C

def rq2_correlations(err, tensile, design):
    """Spearman rho between each tensile metric and the RMSE over the 14 designs,
    for both pairings of Section V-B (same-sample and design-mean)."""
    tested = sorted((s for s in tensile if s['sample'] in tested_samples()), key=lambda s: s['sample'])
    rows = []
    for m in METRICS:
        for est in ESTIMATORS:
            rows.append(dict(metric=m, estimator=est, pairing='design-mean', **spearman(
                [design[d]['tensile_%s_mean' % m] for d in LETTERS],
                [err[d, 'new', 'reg', est]['rmse'] for d in LETTERS])))
            rows.append(dict(metric=m, estimator=est, pairing='same-sample', **spearman(
                [s[m] for s in tested],
                [err[s['design'], 'tensile-tested', 'reg', est]['rmse'] for s in tested])))
    write_csv(config.TABLES / 'fig7_rq2.csv', rows)
    return rows


def tested_samples():
    return {r['sample'] for r in data.bending_recordings() if r['history'] == 'tensile-tested'}


def section_6c(rows, err, tensile, design):
    """Numbers quoted in Section VI-C."""
    of = lambda m: [r for r in rows if r['metric'] == m]
    span = lambda rs: [min(r['rho'] for r in rs), max(r['rho'] for r in rs)]

    # the less sensitive half: the 7 designs whose tensile GF is below the median
    gf = {d: design[d]['tensile_GF_mean'] for d in LETTERS}
    low = [d for d in LETTERS if gf[d] < np.median(list(gf.values()))]
    tested = sorted((s for s in tensile if s['sample'] in tested_samples() and s['design'] in low),
                    key=lambda s: s['sample'])
    half = {}
    for est in ESTIMATORS:
        half[est + '/design-mean'] = float(spearmanr([gf[d] for d in low],
                                                     [err[d, 'new', 'reg', est]['rmse'] for d in low])[0])
        half[est + '/same-sample'] = float(spearmanr([s['GF'] for s in tested],
                                                     [err[s['design'], 'tensile-tested', 'reg', est]['rmse'] for s in tested])[0])

    # the 10-degree classification against the regression, on the new samples
    versus = {}
    for est in ESTIMATORS:
        cls = [err[d, 'new', 'cls', est] for d in LETTERS]
        reg = [err[d, 'new', 'reg', est]['rmse'] for d in LETTERS]
        versus[est] = dict(rank_agreement=float(spearmanr([c['rmse_class'] for c in cls], reg)[0]),
                           cls_rmse_median=float(np.median([c['rmse'] for c in cls])),
                           reg_rmse_median=float(np.median(reg)))
    return {
        'GF_rho_range': span(of('GF')), 'R0_rho_range': span(of('R0')),
        'WR_LR_rho_range': span(of('WR') + of('LR')),
        'H_abs_rho_max': max(abs(r['rho']) for r in of('H')),
        'stab_abs_rho_max': max(abs(r['rho']) for r in of('stab')),
        'GF_strongest': min(of('GF'), key=lambda r: r['rho']),
        'R0_strongest': max(of('R0'), key=lambda r: r['rho']),
        'intervals_excluding_zero': ['%s/%s/%s [%.3f, %.3f]' % (r['metric'], r['estimator'], r['pairing'],
                                                                r['ci_lo'], r['ci_hi'])
                                     for r in rows if r['ci_lo'] > 0 or r['ci_hi'] < 0],
        'less_sensitive_half': dict(GF_median=float(np.median(list(gf.values()))),
                                    designs=[label(d) for d in low], rho=half,
                                    rho_range=[min(half.values()), max(half.values())]),
        'classification_vs_regression': versus,
    }


def fig7(rows):
    rows = {(r['metric'], r['estimator'], r['pairing']): r for r in rows}
    markers = {'mlp': ('o', 'MLP'), 'detr': ('s', 'detrended MLP'), 'rf': ('^', 'RF')}
    # rows ordered by the median |rho| over the six estimates, in three groups of two
    strength = {m: np.median([abs(r['rho']) for (mm, _, _), r in rows.items() if mm == m]) for m in METRICS}
    order = sorted(METRICS, key=lambda m: -strength[m])
    y = [0, 1, 2.45, 3.45, 4.9, 5.9]
    fig, axes = plt.subplots(1, 2, figsize=(3.5, 2.3), sharey=True)
    for ax, pairing in zip(axes, ('design-mean', 'same-sample')):
        for k, m in enumerate(order):
            ink, whisker = (INK, GREY) if k < 2 else ('0.68', '0.82')     # top two in solid ink
            for est, dy in zip(ESTIMATORS, (-0.27, 0, 0.27)):
                r = rows[m, est, pairing]
                ax.plot([r['ci_lo'], r['ci_hi']], [y[k] + dy] * 2, color=whisker, lw=0.55)
                ax.plot(r['rho'], y[k] + dy, markers[est][0], ms=3.2, color=ink, mew=0)
        for x in (-0.5, 0.5):
            ax.axvline(x, color=LIGHT, lw=0.4, zorder=0)
        ax.axvline(0, color='0.33', lw=0.6, zorder=0)
        ax.set_xlim(-1, 1)
        ax.set_title(pairing + ' pairing', fontsize=7.5, pad=2)
        ax.tick_params(axis='y', length=0)
    axes[0].set_xticks([-1, -0.5, 0, 0.5, 1], ['$-1$', '', '0', '', ''])
    axes[1].set_xticks([-1, -0.5, 0, 0.5, 1], ['', '', '0', '', '1'])
    axes[0].set_yticks(y, [LABELS[m] for m in order], fontsize=7.5)
    for k, tick in enumerate(axes[0].get_yticklabels()):
        tick.set_color(INK if k < 2 else '0.6')
    axes[0].set_ylim(y[-1] + 0.5, -0.5)
    for yy, text in ((0.5, 'consistent sign,\nboth pairings'), (2.95, 'same sign,\nweak'), (5.4, 'no association')):
        axes[1].text(1.08, yy, text, transform=axes[1].get_yaxis_transform(), fontsize=6.5, color=GREY, va='center')
    fig.supxlabel(r'Spearman $\rho$ with RMSE', fontsize=7.5, y=0.13)
    from matplotlib.lines import Line2D
    fig.legend([Line2D([], [], ls='', marker=markers[e][0], ms=3.6, color=INK) for e in ESTIMATORS] +
               [Line2D([], [], color=GREY, lw=0.8)],
               [markers[e][1] for e in ESTIMATORS] + ['bootstrap 95 % interval'],
               loc='lower center', ncol=2, frameon=False, fontsize=7, bbox_to_anchor=(0.5, -0.02))
    fig.subplots_adjust(left=0.24, right=0.76, bottom=0.30, top=0.92, wspace=0.12)
    save(fig, 'fig7_rq2')


# ------------------------------------------------------------------ main

def main():
    paper_style()
    tensile = read_csv(config.TABLES / 'samples_tensile.csv')                 # from step 2
    design = {r['design']: r for r in read_csv(config.TABLES / 'table4_electromechanical.csv')}
    err = recording_errors()
    table5(err)
    rows = rq2_correlations(err, tensile, design)
    fig7(rows)
    write_json(config.RESULTS / 'numbers_section6.json', {
        'VI-B': section_6b(err),
        'VI-C': section_6c(rows, err, tensile, design),
    })


if __name__ == '__main__':
    main()
